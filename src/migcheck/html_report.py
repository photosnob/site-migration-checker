"""Self-contained HTML report. No external assets, so it opens offline."""

from __future__ import annotations

import html

from migcheck.catalog import CATALOG
from migcheck.models import Issue, PageResult, Report

_STATUS_CLASS = {
    "BLOCKED": "blocked",
    "NEEDS REVIEW": "review",
    "READY WITH NOTES": "notes",
    "READY": "ready",
}


def render_html(report: Report) -> str:
    status = _STATUS_CLASS.get(report.readiness, "blocked")
    parts = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>migcheck — {_esc(report.readiness)}</title>",
        f"<style>{_CSS}</style>",
        "</head>",
        f'<body class="status-{status}">',
        _header(report, status),
        "<nav>",
        '<a href="#issues">Issues</a>',
        '<a href="#pages">Pages</a>',
        '<a href="#map">Redirect map</a>',
        '<a href="#sitemap">Sitemap</a>',
        '<a href="#robots">Robots</a>',
        '<a href="#suggestions">Suggestions</a>',
        '<a href="#method">Method</a>',
        "</nav>",
        "<main>",
        _issues(report),
        _pages(report),
        _map(report),
        _sitemap(report),
        _robots(report),
        _suggestions(report),
        _method(),
        "</main>",
        "<footer>",
        f"Generated by migcheck {_esc(report.version)} at {_esc(report.generated_at)}. ",
        "Statuses and HTML signals were read from responses. ",
        "This report does not estimate traffic or rankings.",
        "</footer>",
        _SCRIPT,
        "</body>",
        "</html>",
        "",
    ]
    return "\n".join(parts)


def _header(report: Report, status: str) -> str:
    passed = sum(1 for page in report.pages if page.result == "pass")
    warned = sum(1 for page in report.pages if page.result == "warn")
    failed = sum(1 for page in report.pages if page.result == "fail")
    banner = ""
    if report.sample:
        banner = (
            '<p class="banner">SAMPLE. Synthetic fixture. '
            "These findings are not a measurement of a live site.</p>"
        )
    disclaimer = f"<p class='disclaimer'>{_esc(report.disclaimer)}</p>" if report.disclaimer else ""
    inputs = "".join(f"<li>{_esc(item)}</li>" for item in report.inputs)
    counts = "".join(
        f"<li><span class='sev {name}'>{name}</span> {report.counts[name]}</li>"
        for name in ("critical", "high", "medium", "low", "info")
    )
    return f"""
<header>
  <p class="mark">migcheck <span>migration readiness</span></p>
  <h1>Go-live readiness</h1>
  {banner}
  <p class="readiness {status}">{_esc(report.readiness)}</p>
  <p class="reason">{_esc(report.readiness_reason)}</p>
  {disclaimer}
  <dl class="meta">
    <div><dt>Mode</dt><dd>{_esc(report.mode)}</dd></div>
    <div><dt>New host</dt><dd>{_esc(report.new_host)}</dd></div>
    <div><dt>Old URLs</dt><dd>{report.url_count}</dd></div>
    <div><dt>Rules</dt><dd>{report.rule_count} ({report.wildcard_rules} wildcard)</dd></div>
    <div><dt>Pages</dt><dd>{passed} pass · {warned} warn · {failed} fail</dd></div>
    <div><dt>Generated</dt><dd>{_esc(report.generated_at)}</dd></div>
  </dl>
  <ul class="counts">{counts}</ul>
  <h2>Inputs</h2>
  <ul class="inputs">{inputs}</ul>
</header>
"""


def _issues(report: Report) -> str:
    rows = "\n".join(_issue_row(issue) for issue in report.issues) or "<p>No issues.</p>"
    return f"""
<section id="issues">
  <h2>Issues</h2>
  <label class="filter">Filter <input id="q" type="search" placeholder="URL, code, or message"></label>
  <div class="issue-list">{rows}</div>
</section>
"""


def _issue_row(issue: Issue) -> str:
    blob = " ".join(
        (issue.severity.value, issue.code, issue.url, issue.message, issue.detail)
    ).lower()
    detail = f"<p class='detail'>{_esc(issue.detail)}</p>" if issue.detail else ""
    url = f"<p class='url'>{_esc(issue.url)}</p>" if issue.url else ""
    return f"""
<article class="issue" data-filter="{_esc(blob)}">
  <p class="kicker"><span class="sev {issue.severity.value}">{_esc(issue.severity.value)}</span>
  <span class="code">{_esc(issue.code)}</span>
  <span class="source">{_esc(issue.source)}</span></p>
  {url}
  <p>{_esc(issue.message)}</p>
  {detail}
</article>
"""


def _pages(report: Report) -> str:
    body = "\n".join(_page_row(page) for page in report.pages)
    details = "\n".join(_page_detail(page) for page in report.pages if page.result != "pass")
    return f"""
<section id="pages">
  <h2>Pages</h2>
  <p class="note">Input clicks and impressions come from the URL file. migcheck does not measure traffic.</p>
  <table>
    <thead>
      <tr>
        <th scope="col">Result</th>
        <th scope="col">Old URL</th>
        <th scope="col">Final</th>
        <th scope="col">Issues</th>
        <th scope="col">Input clicks</th>
      </tr>
    </thead>
    <tbody>
      {body}
    </tbody>
  </table>
  <h3>Pages that are not a clean pass</h3>
  {details or "<p>None.</p>"}
</section>
"""


def _page_row(page: PageResult) -> str:
    codes = " ".join(issue.code for issue in page.issues) or "—"
    clicks = "—" if page.clicks is None else str(page.clicks)
    return f"""
<tr data-filter="{_esc(page.old_url.lower())}">
  <td><span class="result {page.result}">{page.result}</span></td>
  <td class="url">{_esc(page.old_url)}</td>
  <td class="url">{_esc(page.final_url or "—")}</td>
  <td>{_esc(codes)}</td>
  <td>{_esc(clicks)}</td>
</tr>
"""


def _page_detail(page: PageResult) -> str:
    hops = "".join(
        f"<li>{_esc(hop.status)} {_esc(hop.url)}"
        + (f" → {_esc(hop.location)}" if hop.location else "")
        + (f" ({_esc(hop.error)})" if hop.error else "")
        + "</li>"
        for hop in page.hops
    )
    issues = "".join(
        f"<li><strong>{_esc(issue.code)}</strong> {_esc(issue.message)}</li>"
        for issue in page.issues
    )
    signals = _signals(page)
    return f"""
<article class="page" data-filter="{_esc(page.old_url.lower())}">
  <h3 class="url">{_esc(page.old_url)}</h3>
  <p><span class="result {page.result}">{page.result}</span>
  Expected <span class="url">{_esc(page.expected_url)}</span></p>
  <ol class="hops">{hops}</ol>
  <ul>{issues}</ul>
  {signals}
</article>
"""


def _signals(page: PageResult) -> str:
    old, new = page.old_signals, page.new_signals
    if old is None and new is None:
        return ""

    def cell(value: object) -> str:
        if value is None or value == "":
            return "—"
        return _esc(value)

    rows = [
        ("Title", None if old is None else old.title, None if new is None else new.title),
        (
            "Description",
            None if old is None else old.description,
            None if new is None else new.description,
        ),
        ("H1", None if old is None else old.h1, None if new is None else new.h1),
        ("Words", None if old is None else old.word_count, None if new is None else new.word_count),
        ("Canonical", "—", None if new is None else new.canonical),
        ("noindex", "—", None if new is None else new.noindex),
    ]
    body = "".join(
        f"<tr><th scope='row'>{_esc(name)}</th><td>{cell(left)}</td><td>{cell(right)}</td></tr>"
        for name, left, right in rows
    )
    return f"""
<table class="signals">
  <thead><tr><th scope="col"></th><th scope="col">Old</th><th scope="col">New</th></tr></thead>
  <tbody>{body}</tbody>
</table>
"""


def _map(report: Report) -> str:
    rows = "".join(
        "<tr>"
        f"<td>{rule.line}</td>"
        f"<td class='url'>{_esc(rule.source)}</td>"
        f"<td class='url'>{_esc(rule.target)}</td>"
        f"<td>{rule.status}</td>"
        f"<td>{'yes' if rule.wildcard else ''}</td>"
        f"<td>{_esc(rule.unsupported or '')}</td>"
        "</tr>"
        for rule in report.rules
    )
    return f"""
<section id="map">
  <h2>Redirect map</h2>
  <p class="note">First match wins. Wildcard targets are not requested individually.</p>
  <table>
    <thead>
      <tr><th scope="col">Line</th><th scope="col">Source</th><th scope="col">Target</th>
      <th scope="col">Status</th><th scope="col">Wildcard</th><th scope="col">Note</th></tr>
    </thead>
    <tbody>{rows or "<tr><td colspan='6'>No redirect map was supplied.</td></tr>"}</tbody>
  </table>
</section>
"""


def _sitemap(report: Report) -> str:
    listed = "".join(f"<li class='url'>{_esc(url)}</li>" for url in report.new_sitemap_urls)
    extras = "".join(f"<li class='url'>{_esc(url)}</li>" for url in report.extra_sitemap_urls)
    return f"""
<section id="sitemap">
  <h2>New sitemap</h2>
  <p>{len(report.new_sitemap_urls)} URL(s). Membership ignores scheme and a single trailing slash.</p>
  <h3>In the new sitemap, not a destination of the old list</h3>
  <ul>{extras or "<li>None.</li>"}</ul>
  <h3>All new sitemap URLs</h3>
  <ul>{listed or "<li>None.</li>"}</ul>
</section>
"""


def _robots(report: Report) -> str:
    body = report.robots_body or ""
    block = f"<pre>{_esc(body)}</pre>" if body else "<p>No robots.txt body was captured.</p>"
    return f"""
<section id="robots">
  <h2>robots.txt</h2>
  <p class="note">Rules are the group Googlebot would use: the longest matching user-agent, otherwise *.</p>
  {block}
</section>
"""


def _suggestions(report: Report) -> str:
    if not report.suggestions:
        rows = "<p>No suggestion cleared the similarity threshold.</p>"
    else:
        rows = "".join(
            "<tr>"
            f"<td class='url'>{_esc(item.old_url)}</td>"
            f"<td class='url'>{_esc(item.candidate_url)}</td>"
            f"<td>{item.score:.2f}</td>"
            f"<td>{_esc(item.via)}</td>"
            f"<td>{_esc(item.old_label)}</td>"
            f"<td>{_esc(item.candidate_label)}</td>"
            "</tr>"
            for item in report.suggestions
        )
        rows = f"""
<table>
  <thead>
    <tr><th scope="col">Old URL</th><th scope="col">Candidate</th><th scope="col">Score</th>
    <th scope="col">Via</th><th scope="col">Old label</th><th scope="col">Candidate label</th></tr>
  </thead>
  <tbody>{rows}</tbody>
</table>
"""
    return f"""
<section id="suggestions">
  <h2>Suggestions</h2>
  <p class="note">Suggestions do not change readiness. They are similarity matches for unmapped URLs that did not land.</p>
  {rows}
</section>
"""


def _method() -> str:
    items = "".join(
        f"<dt>{_esc(code)}</dt><dd><span class='sev {severity.value}'>{severity.value}</span> {_esc(text)}</dd>"
        for code, (severity, text) in CATALOG.items()
    )
    return f"""
<section id="method">
  <h2>How a result was decided</h2>
  <ul>
    <li>Staging mode requests each old path on the new host. Live mode requests the old URL as published.</li>
    <li>Redirects are followed one hop at a time. A loop or the hop cap stops the walk. The client does not hide hops.</li>
    <li>With a redirect map, the expected page is the first matching rule. Without one, the same path on the new host is expected.</li>
    <li>A single 301 or 308 to that page is the permanent-move shape. 302, 303, and 307 are flagged even if the page is right.</li>
    <li>Homepage redirects from any other path are soft-404 risks. Protocol and trailing-slash differences are separate from a wrong path.</li>
    <li>Content is read from the response HTML. JavaScript is not executed. Word count is whitespace-separated visible text, excluding head, script, and style.</li>
    <li>When a rule names a destination, content is compared to that destination even if the server currently sends people somewhere else.</li>
    <li>Readiness is BLOCKED on any critical issue, NEEDS REVIEW on high issues, READY WITH NOTES on medium or low issues, and READY otherwise. Info and suggestions do not block.</li>
  </ul>
  <h3>Issue codes</h3>
  <dl class="glossary">{items}</dl>
</section>
"""


def _esc(value: object) -> str:
    return html.escape("" if value is None else str(value), quote=True)


